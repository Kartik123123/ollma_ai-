"""Turns a list of successfully-resolved steps into a standalone,
reusable pytest + Selenium test file that needs no LLM to run again.

Steps that captured a value from a live API response (e.g. an OTP) are
re-captured fresh on every replay - the old captured value is never
hardcoded, since things like OTPs expire.
"""

import re

TEMPLATE_HEADER = '''"""
Auto-generated by the AI-assisted Selenium automation framework.
This file needs NO Ollama / LLM to run - it replays the exact locators
that were resolved during the recorded session. Any value captured from
a live API response (e.g. an OTP) is re-captured fresh on every run.
"""

import base64
import json
import re
import time

import pytest
from selenium import webdriver
from selenium.webdriver.chrome.options import Options
from selenium.webdriver.common.by import By
from selenium.webdriver.support.ui import WebDriverWait, Select
from selenium.webdriver.support import expected_conditions as EC


BY_MAP = {{
    "ID": By.ID,
    "NAME": By.NAME,
    "CSS_SELECTOR": By.CSS_SELECTOR,
    "XPATH": By.XPATH,
}}

_PATH_TOKEN = re.compile(r"([^.\\[\\]]+)|\\[(\\d+)\\]")


def _traverse(data, path):
    current = data
    for name, idx in _PATH_TOKEN.findall(path):
        if name:
            current = current[name]
        elif idx != "":
            current = current[int(idx)]
    return current


def capture_json_field(driver, url_contains, json_path, timeout=15, poll_interval=0.5):
    deadline = time.time() + timeout
    seen_request_ids = set()
    while time.time() < deadline:
        try:
            logs = driver.get_log("performance")
        except Exception:
            logs = []
        for entry in logs:
            try:
                message = json.loads(entry["message"])["message"]
            except Exception:
                continue
            if message.get("method") != "Network.responseReceived":
                continue
            params = message.get("params", {{}})
            response = params.get("response", {{}})
            url = response.get("url", "")
            request_id = params.get("requestId")
            if url_contains not in url or request_id in seen_request_ids:
                continue
            seen_request_ids.add(request_id)
            try:
                body_result = driver.execute_cdp_cmd("Network.getResponseBody", {{"requestId": request_id}})
            except Exception:
                continue
            body_text = body_result.get("body", "")
            if body_result.get("base64Encoded"):
                try:
                    body_text = base64.b64decode(body_text).decode("utf-8", errors="ignore")
                except Exception:
                    continue
            try:
                data = json.loads(body_text)
            except Exception:
                continue
            try:
                value = _traverse(data, json_path)
            except Exception:
                continue
            if value is not None:
                return str(value)
        time.sleep(poll_interval)
    return None


@pytest.fixture
def driver():
    options = Options()
    options.add_argument("--start-maximized")
    options.set_capability("goog:loggingPrefs", {{"performance": "ALL"}})
    drv = webdriver.Chrome(options=options)
    drv.execute_cdp_cmd("Network.enable", {{}})
    yield drv
    drv.quit()


def test_generated_flow(driver):
    driver.get("{url}")
    wait = WebDriverWait(driver, 10)
'''

TEMPLATE_FOOTER = "\n"


def _sanitize_var(name: str) -> str:
    return re.sub(r"\W", "_", name).upper() or "VALUE"


def _step_to_code(step: dict) -> str:
    instruction = step["instruction"].replace('"', "'")
    action = step["action"]
    value = step.get("value")
    locator = step.get("locator")
    value_var = step.get("value_var")

    lines = [f"\n    # Step: {instruction}"]

    if action == "capture_api_value":
        var_name = _sanitize_var(step.get("store_as", "VALUE"))
        url_contains = (step.get("url_contains") or "").replace('"', "'")
        json_path = (step.get("json_path") or "").replace('"', "'")
        lines.append(
            f'    {var_name} = capture_json_field(driver, "{url_contains}", "{json_path}", timeout=15)'
        )
        lines.append(f'    assert {var_name} is not None, "Timed out waiting to capture {var_name}"')
        return "\n".join(lines)

    if action == "wait":
        lines.append(f"    time.sleep({float(value) if value else 2})")
        return "\n".join(lines)

    if action == "navigate":
        lines.append(f'    driver.get("{value}")')
        return "\n".join(lines)

    if action == "assert_text":
        safe_value = value.replace('"', "'") if value else ""
        lines.append(f'    wait.until(lambda d: "{safe_value}" in d.page_source)')
        return "\n".join(lines)

    if not locator:
        lines.append("    # SKIPPED: no reliable locator was recorded for this step")
        return "\n".join(lines)

    by = locator["by"]
    loc_value = locator["value"].replace('"', "'")
    lines.append(f'    el = wait.until(EC.presence_of_element_located((BY_MAP["{by}"], "{loc_value}")))')

    # If this step's value came from a captured variable (e.g. {OTP}),
    # reference the live Python variable instead of hardcoding the old value.
    value_expr = _sanitize_var(value_var) if value_var else None

    if action in ("click", "submit"):
        lines.append("    el.click()")
    elif action == "type":
        lines.append("    el.clear()")
        if value_expr:
            lines.append(f"    el.send_keys({value_expr})")
        else:
            safe_value = (value or "").replace('"', "'")
            lines.append(f'    el.send_keys("{safe_value}")')
    elif action == "select":
        if value_expr:
            lines.append(f"    Select(el).select_by_visible_text({value_expr})")
        else:
            safe_value = (value or "").replace('"', "'")
            lines.append(f'    Select(el).select_by_visible_text("{safe_value}")')
    elif action == "hover":
        lines.append("    from selenium.webdriver.common.action_chains import ActionChains")
        lines.append("    ActionChains(driver).move_to_element(el).perform()")
    elif action == "assert_visible":
        lines.append("    assert el.is_displayed()")

    return "\n".join(lines)


def generate_pytest_file(url: str, steps: list, output_path: str):
    body = [TEMPLATE_HEADER.format(url=url)]
    for step in steps:
        if step["status"] == "fail":
            body.append(f"\n    # SKIPPED (failed during recording): {step['instruction']}")
            continue
        body.append(_step_to_code(step))
    body.append(TEMPLATE_FOOTER)

    with open(output_path, "w", encoding="utf-8") as f:
        f.write("".join(body))
